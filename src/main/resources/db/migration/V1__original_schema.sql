CREATE TABLE IF NOT EXISTS users (
  id BIGINT PRIMARY KEY AUTO_INCREMENT, username VARCHAR(40) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL,
  real_name VARCHAR(40) NOT NULL, phone VARCHAR(20) NOT NULL, role VARCHAR(20) NOT NULL,
  enabled TINYINT(1) NOT NULL DEFAULT 1, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_user_role CHECK (role IN ('STUDENT','MERCHANT','RIDER','ADMIN'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS shops (
  id BIGINT PRIMARY KEY AUTO_INCREMENT, owner_id BIGINT NOT NULL UNIQUE, name VARCHAR(80) NOT NULL,
  description VARCHAR(255), is_open TINYINT(1) NOT NULL DEFAULT 1,
  CONSTRAINT fk_shop_owner FOREIGN KEY(owner_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS dishes (
  id BIGINT PRIMARY KEY AUTO_INCREMENT, shop_id BIGINT NOT NULL, category VARCHAR(40) NOT NULL,
  name VARCHAR(80) NOT NULL, price DECIMAL(10,2) NOT NULL, image_path VARCHAR(255), on_sale TINYINT(1) NOT NULL DEFAULT 1,
  CONSTRAINT fk_dish_shop FOREIGN KEY(shop_id) REFERENCES shops(id), CONSTRAINT ck_dish_price CHECK(price >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS addresses (
  id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL, building VARCHAR(80) NOT NULL, room VARCHAR(40) NOT NULL,
  contact_name VARCHAR(40) NOT NULL, phone VARCHAR(20) NOT NULL, is_default TINYINT(1) NOT NULL DEFAULT 0,
  CONSTRAINT fk_address_user FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS orders (
  id BIGINT PRIMARY KEY AUTO_INCREMENT, order_no VARCHAR(32) NOT NULL UNIQUE, student_id BIGINT NOT NULL, shop_id BIGINT NOT NULL,
  rider_id BIGINT NULL, amount DECIMAL(10,2) NOT NULL, address_snapshot VARCHAR(255) NOT NULL,
  status VARCHAR(24) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  paid_at TIMESTAMP NULL, accepted_at TIMESTAMP NULL, ready_at TIMESTAMP NULL, delivered_at TIMESTAMP NULL, completed_at TIMESTAMP NULL,
  CONSTRAINT fk_order_student FOREIGN KEY(student_id) REFERENCES users(id), CONSTRAINT fk_order_shop FOREIGN KEY(shop_id) REFERENCES shops(id),
  CONSTRAINT fk_order_rider FOREIGN KEY(rider_id) REFERENCES users(id), CONSTRAINT ck_order_status CHECK(status IN ('UNPAID','PENDING_ACCEPT','MAKING','READY','DELIVERING','WAIT_CONFIRM','COMPLETED','CANCELED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS order_items (
  id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL, dish_id BIGINT NOT NULL, dish_name VARCHAR(80) NOT NULL,
  unit_price DECIMAL(10,2) NOT NULL, quantity INT NOT NULL, subtotal DECIMAL(10,2) NOT NULL,
  CONSTRAINT fk_item_order FOREIGN KEY(order_id) REFERENCES orders(id), CONSTRAINT fk_item_dish FOREIGN KEY(dish_id) REFERENCES dishes(id), CONSTRAINT ck_item_quantity CHECK(quantity > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS order_events (
  id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL, from_status VARCHAR(24), to_status VARCHAR(24) NOT NULL,
  operator_id BIGINT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_event_order FOREIGN KEY(order_id) REFERENCES orders(id), CONSTRAINT fk_event_operator FOREIGN KEY(operator_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
